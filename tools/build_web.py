#!/usr/bin/env python3
"""Embed the esp-web-sdr viewer into src/web_assets.h (gzipped).

    python tools/build_web.py                  # -> src/web_assets.h
    python tools/build_web.py --dist build/web # patched files, for ws_bridge.py

web/esp-web-sdr/ holds pristine upstream files (see UPSTREAM.txt). Only the
transport changes: serial-transport.js (WebSerial/WebUSB) is replaced by
web/ws-transport.js, which talks to the firmware's /ws WebSocket. Every patch
below must match exactly once, so refreshing upstream fails loudly instead of
silently shipping a half-patched page.
"""
import gzip
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
upstream = root / "web" / "esp-web-sdr"

PATCHES = {
    "index.html": [
        ('<script defer src="serial-transport.js"></script>', '<script defer src="ws-transport.js"></script>'),
        ("<title>ESP-WebSDR · USB receiver</title>", "<title>ESP-WebSDR · TTGO WiFi receiver</title>"),
        ("<span>Raw IQ Capture with Espressif's ESP32 Chips</span>",
         "<span>Raw IQ Capture with Espressif's ESP32 Chips · TTGO T-Display over WiFi</span>"),
        ('role="menuitem">Connect to Last Device</button', 'role="menuitem">Connect to TTGO SDR</button'),
        # no WebSerial/WebUSB/flasher on the device's own access point
        ('<button id="openOther" type="button" role="menuitem">', '<button id="openOther" type="button" role="menuitem" hidden>'),
        ('<button id="openUSB" type="button" role="menuitem">', '<button id="openUSB" type="button" role="menuitem" hidden>'),
        ('<a id="openFlasher" role="menuitem"', '<a id="openFlasher" role="menuitem" hidden'),
    ],
    "radio.js": [
        ("if (!isSecureContext) throw Error('Serve this page over HTTPS or localhost.');",
         "if (!isSecureContext && !SerialConnection.insecureOk)\n      throw Error('Serve this page over HTTPS or localhost.');"),
    ],
    "app.js": [
        ("`kB/s ${radio.transport} · ",
         "`kB/s ${SerialConnection.kind(radio.port || {}) === 'websocket' ? 'WiFi' : radio.transport} · "),
    ],
}

# (URL path, source file, content type)
ASSETS = [
    ("/index.html", upstream / "index.html", "text/html; charset=utf-8"),
    ("/app.js", upstream / "app.js", "text/javascript"),
    ("/radio.js", upstream / "radio.js", "text/javascript"),
    ("/ws-transport.js", root / "web" / "ws-transport.js", "text/javascript"),
    ("/style.css", upstream / "style.css", "text/css"),
    ("/fonts.css", upstream / "fonts.css", "text/css"),
    ("/espargos-logo.svg", upstream / "espargos-logo.svg", "image/svg+xml"),
    ("/favicon-16x16.png", upstream / "favicon-16x16.png", "image/png"),
    ("/favicon-32x32.png", upstream / "favicon-32x32.png", "image/png"),
    ("/favicon-194x194.png", upstream / "favicon-194x194.png", "image/png"),
]


def patched(path: pathlib.Path) -> bytes:
    data = path.read_bytes()
    if path.parent != upstream or path.name not in PATCHES:
        return data
    text = data.decode("utf-8")
    for old, new in PATCHES[path.name]:
        count = text.count(old)
        if count != 1:
            sys.exit(f"{path.name}: patch target found {count} times (upstream changed?):\n  {old}")
        text = text.replace(old, new)
    return text.encode("utf-8")


def write_dist(dist: pathlib.Path) -> None:
    """The patched page as plain files (tools/ws_bridge.py serves them)."""
    dist.mkdir(parents=True, exist_ok=True)
    for url, src, _ in ASSETS:
        (dist / url.lstrip("/")).write_bytes(patched(src))
    print(f"{dist}: {len(ASSETS)} files")


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "--dist":
        write_dist(pathlib.Path(sys.argv[2]))
        return
    out = root / "src" / "web_assets.h"
    lines = [
        "/* generated by tools/build_web.py from web/ — do not edit */",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "typedef struct {",
        "    const char *path, *type;",
        "    const uint8_t *data;",
        "    size_t len;",
        "} web_asset_t;",
    ]
    table, raw_total, gz_total = [], 0, 0
    for i, (url, src, ctype) in enumerate(ASSETS):
        raw = patched(src)
        gz = gzip.compress(raw, 9, mtime=0)
        raw_total += len(raw)
        gz_total += len(gz)
        lines.append(f"static const uint8_t web_asset_{i}[{len(gz)}] = {{ /* {url} */")
        for k in range(0, len(gz), 20):
            lines.append("    " + ",".join(str(b) for b in gz[k:k + 20]) + ",")
        lines.append("};")
        table.append(f'    {{"{url}", "{ctype}", web_asset_{i}, sizeof(web_asset_{i})}},')
    lines.append("static const web_asset_t web_assets[] = {")
    lines += table
    lines.append("};")
    lines.append("static const size_t web_asset_count = sizeof(web_assets) / sizeof(web_assets[0]);")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out.relative_to(root)}: {len(ASSETS)} files, {raw_total} -> {gz_total} bytes gzipped")


if __name__ == "__main__":
    main()
